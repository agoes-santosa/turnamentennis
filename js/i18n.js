export function makeT(lang) {
  const d = DICT[lang] ?? DICT.id;
  const t = (k) => d[k] ?? DICT.en[k] ?? k;
  t.stage = (s) => (STAGE_LABEL[lang] ?? STAGE_LABEL.id)[s] ?? s;
  t.stageShort = (s) => (STAGE_SHORT[lang] ?? STAGE_SHORT.id)[s] ?? s;
  t.lang = lang;
  return t;
}
